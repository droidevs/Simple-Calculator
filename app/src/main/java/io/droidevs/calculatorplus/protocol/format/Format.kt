package io.droidevs.calcus.domain.model.protocol.format

class Format {
    companion object {
        // Trigonometric functions
        const val SIN = "s"
        const val COS = "c"
        const val TAN = "t"

        // Logarithmic function
        const val LOG = "l"

        // Inverse trigonometric functions
        const val ACOS = "k"
        const val ASIN = "m"
        const val ATAN = "n"

        // Hyperbolic trigonometric functions
        const val COSH = "o"
        const val SINH = "p"
        const val TANH = "q"

        // Inverse hyperbolic trigonometric functions
        const val ACOSH = "r"
        const val ASINH = "v"
        const val ATANH = "w"
    }
}